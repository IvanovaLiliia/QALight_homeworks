package java_hw_2;

public class Greater_less_numbers {
    public static void main(String[] args) {


        int a = 100;
        int b = 60;

        if (a > b) {
            System.out.println(a + " is greater than " + b);
        }
        else if (a < b)

            System.out.println(a + " is less than " + b);
        else
            System.out.println( "The numbers are equal");
    }
}
